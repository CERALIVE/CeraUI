function displayNames(locale: string): Intl.DisplayNames | undefined {
	try {
		return new Intl.DisplayNames([locale], { type: "region" });
	} catch {
		return undefined;
	}
}

/**
 * Localized, name-sorted country options, with the world domain leading.
 * Falls back to the bare code when the runtime cannot name a region.
 */
export function countryOptions(
	locale: string,
	worldLabel: string,
): CountryOption[] {
	const names = displayNames(locale);
	const collator = new Intl.Collator(locale);

	const countries = ISO_3166_1_ALPHA2.map((code) => ({
		code,
		name: names?.of(code) ?? code,
	})).sort((a, b) => collator.compare(a.name, b.name));

	return [{ code: WORLD_REGULATORY_DOMAIN, name: worldLabel }, ...countries];
}

export function findCountryName(
	options: readonly CountryOption[],
	code: string | undefined,
): string | undefined {
	if (code === undefined) return undefined;
	return options.find((o) => o.code === code)?.name;
}

/** Case- and accent-insensitive match on either the name or the code. */
export function filterCountries(
	options: readonly CountryOption[],
	query: string,
): CountryOption[] {
	const needle = query.trim().toLocaleLowerCase();
	if (needle === "") return [...options];

	return options.filter(
		(o) =>
			o.code.toLocaleLowerCase().includes(needle) ||
			o.name.toLocaleLowerCase().includes(needle),
	);
}
